-- Run second, after STAGE.sql, in the same isolated exercise database.
-- The source schema contains only raw tables; reporting choices belong here.
CREATE SCHEMA IF NOT EXISTS DWH_SCHEMA;

-- Exercise reporting bounds, not incoming data or evidence of completeness.
-- Keep the calendar setup and analytical queries on the same date ranges.
CREATE OR REPLACE VIEW DWH_SCHEMA.reporting_scope AS
SELECT source_code, report_start, report_end
FROM (VALUES
    ('SNOWFLAKE'::text, DATE '2026-04-01', DATE '2026-10-31'),
    ('DATAIKU'::text, DATE '2026-08-01', DATE '2026-08-31')
) AS bounds (source_code, report_start, report_end);

CREATE TABLE IF NOT EXISTS DWH_SCHEMA.dim_source (
    source_id smallint PRIMARY KEY,
    source_code text UNIQUE NOT NULL,
    record_semantics text NOT NULL,
    cost_basis text NOT NULL
  );

CREATE TABLE IF NOT EXISTS DWH_SCHEMA.dim_date (
    date_key integer PRIMARY KEY,
    calendar_date date UNIQUE NOT NULL,
    month_start date NOT NULL
  );

CREATE TABLE IF NOT EXISTS DWH_SCHEMA.dim_user (
    user_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code text NOT NULL,
    user_nk text NOT NULL,
    UNIQUE (source_code, user_nk)
  );

CREATE TABLE IF NOT EXISTS DWH_SCHEMA.dim_entity (
    entity_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code text NOT NULL,
    entity_nk text NOT NULL,
    entity_type text NOT NULL,
    environment_label text NOT NULL,
    UNIQUE (source_code, entity_nk, environment_label)
  );

CREATE TABLE IF NOT EXISTS DWH_SCHEMA.dim_model (
    model_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code text NOT NULL,
    model_name text NOT NULL,
    UNIQUE (source_code, model_name)
  );

CREATE TABLE IF NOT EXISTS DWH_SCHEMA.fact_usage (
 batch_id text NOT NULL,row_no integer NOT NULL,
 source_id smallint NOT NULL REFERENCES DWH_SCHEMA.dim_source,
 date_key integer NOT NULL REFERENCES DWH_SCHEMA.dim_date,
 user_key bigint NOT NULL,entity_key bigint NOT NULL,model_key bigint NOT NULL,
 started_at timestamp NOT NULL,ended_at timestamp,source_view text,query_id text,
 function_name text,llm_type text,llm_connection text,
 cost_usd numeric(20,9) CHECK (cost_usd>=0 AND cost_usd<>'NaN'::numeric),
 total_tokens bigint CHECK (total_tokens>=0),prompt_tokens bigint CHECK (prompt_tokens>=0),
 completion_tokens bigint CHECK (completion_tokens>=0),status text,
 token_consistent boolean,quality_flags text[] NOT NULL,
 PRIMARY KEY (batch_id,row_no),CHECK (ended_at IS NULL OR ended_at>=started_at),
 FOREIGN KEY (user_key) REFERENCES DWH_SCHEMA.dim_user(user_key),
 FOREIGN KEY (entity_key) REFERENCES DWH_SCHEMA.dim_entity(entity_key),
 FOREIGN KEY (model_key) REFERENCES DWH_SCHEMA.dim_model(model_key)
);



-- S04A: load dimensions = the distinct descriptive values referenced by facts.
-- Source is part of each natural identity: the same text in two systems does
-- not establish that it identifies the same person, entity, or model.
-- ON CONFLICT DO NOTHING lets us rerun without inserting the same identity twice.
INSERT INTO DWH_SCHEMA.dim_source (source_id, source_code, record_semantics, cost_basis)
VALUES
    (1, 'SNOWFLAKE', 'Reported source observation; query grain unverified', 'Reported USD'),
    (2, 'DATAIKU', 'Reported source observation; not a certified agent run', 'Estimated USD')
ON CONFLICT DO NOTHING;

-- Supplied calendar setup: include dates with no observed rows for later reports.
-- A calendar date does not establish that we received all data for that day.
INSERT INTO DWH_SCHEMA.dim_date (date_key, calendar_date, month_start)
SELECT to_char(d, 'YYYYMMDD')::integer,
       d::date,
       date_trunc('month', d)::date
FROM (
    SELECT min(report_start) - interval '1 month' AS lo, max(report_end) AS hi
    FROM DWH_SCHEMA.reporting_scope
) AS scope
CROSS JOIN LATERAL generate_series(scope.lo, scope.hi, interval '1 day') AS d
ON CONFLICT DO NOTHING;

-- user_nk comes from the source. user_key is generated by the DWH (IDENTITY).
INSERT INTO DWH_SCHEMA.dim_user (source_code, user_nk)
SELECT DISTINCT source_code, user_nk
FROM STAGE_SCHEMA.usage
ON CONFLICT DO NOTHING;

INSERT INTO DWH_SCHEMA.dim_entity (source_code, entity_nk, entity_type, environment_label)
SELECT DISTINCT source_code, entity_nk, entity_type, environment_label
FROM STAGE_SCHEMA.usage
ON CONFLICT DO NOTHING;

INSERT INTO DWH_SCHEMA.dim_model (source_code, model_name)
SELECT DISTINCT source_code, model_name
FROM STAGE_SCHEMA.usage
ON CONFLICT DO NOTHING;

-- Insert each imported record once. Repeating this fixed sample skips existing
-- (batch_id, row_no) pairs; it does not refresh facts after source edits.
-- Batch labels must be unique across both feeds (here sf-... versus dk-...).
INSERT INTO DWH_SCHEMA.fact_usage (
    batch_id, row_no, source_id, date_key, user_key, entity_key, model_key,
    started_at, ended_at, source_view, query_id, function_name,
    llm_type, llm_connection, cost_usd, total_tokens, prompt_tokens,
    completion_tokens, status, token_consistent, quality_flags
)
SELECT
    t.batch_id,
    t.row_no,
    s.source_id,
    to_char(t.started_at, 'YYYYMMDD')::integer,
    u.user_key,
    e.entity_key,
    m.model_key,
    t.started_at,
    t.ended_at,
    t.source_view,
    t.query_id,
    t.function_name,
    t.llm_type,
    t.llm_connection,
    t.cost_usd,
    t.total_tokens,
    t.prompt_tokens,
    t.completion_tokens,
    NULL, -- Neither source supplied a status.
    t.token_consistent,
    t.quality_flags
FROM STAGE_SCHEMA.usage AS t
JOIN DWH_SCHEMA.dim_source AS s
  ON s.source_code = t.source_code
JOIN DWH_SCHEMA.dim_user AS u
  ON u.source_code = t.source_code AND u.user_nk = t.user_nk
JOIN DWH_SCHEMA.dim_entity AS e
  ON e.source_code = t.source_code AND e.entity_nk = t.entity_nk
 AND e.environment_label = t.environment_label
JOIN DWH_SCHEMA.dim_model AS m
  ON m.source_code = t.source_code AND m.model_name = t.model_name
ON CONFLICT (batch_id, row_no) DO NOTHING;
